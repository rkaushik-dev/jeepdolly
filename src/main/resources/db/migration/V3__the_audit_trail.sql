-- The audit trail, which arrived once the interface had people behind it.
--
-- Ported from Alembic revision 0003, every table, column, index and constraint under the name the
-- original gave it. The serial key is an identity column, as SQLite's integer primary key was:
-- audit_trail.id.

CREATE TABLE audit_trail (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    happened TIMESTAMP NOT NULL,
    action VARCHAR(32) NOT NULL,
    actor VARCHAR(120) NOT NULL,
    kind VARCHAR(32) NOT NULL,
    reference VARCHAR(32) NOT NULL,
    detail VARCHAR(500) NOT NULL,
    CONSTRAINT pk_audit_trail PRIMARY KEY (id),
    CONSTRAINT ck_audit_trail_action_not_empty CHECK (length(action) > 0),
    CONSTRAINT ck_audit_trail_actor_not_empty CHECK (length(actor) > 0)
);

CREATE INDEX ix_audit_trail_action ON audit_trail (action);

CREATE INDEX ix_audit_trail_actor ON audit_trail (actor);

CREATE INDEX ix_audit_trail_happened ON audit_trail (happened);

CREATE INDEX ix_audit_trail_reference ON audit_trail (reference);
