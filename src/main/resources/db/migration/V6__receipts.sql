-- Receipts, which are the other half of a permit.
--
-- Every constraint and index is named by the schema's convention: pk_, uq_, ix_, fk_ and ck_. Money
-- is whole cents in BIGINT: receipts.amount. The serial key is an identity column for receipts.id.

CREATE TABLE receipts (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    permit VARCHAR(32) NOT NULL,
    taken DATE NOT NULL,
    method VARCHAR(32) NOT NULL,
    amount BIGINT,
    taken_by VARCHAR(120) NOT NULL,
    reference VARCHAR(32) NOT NULL,
    note VARCHAR(500) NOT NULL,
    CONSTRAINT pk_receipts PRIMARY KEY (id),
    CONSTRAINT fk_receipts_permit_permits FOREIGN KEY (permit) REFERENCES permits (number),
    CONSTRAINT ck_receipts_amount_not_nothing CHECK (amount <> 0),
    CONSTRAINT ck_receipts_method_not_empty CHECK (length(method) > 0)
);

CREATE INDEX ix_receipts_method ON receipts (method);

CREATE INDEX ix_receipts_permit ON receipts (permit);

CREATE INDEX ix_receipts_taken ON receipts (taken);
